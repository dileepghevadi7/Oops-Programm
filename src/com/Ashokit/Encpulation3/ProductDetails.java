package com.Ashokit.Encpulation3;

public class ProductDetails {

	private int id;
	private String ProductName;
	private String ProductStutus;

	public int getId() {
		return id;
	}

	public void setId(int id) {
		this.id = id;
	}

	public String getProductName() {
		return ProductName;
	}

	public void setProductName(String productName) {
		ProductName = productName;
	}

	public String getProductStutus() {
		return ProductStutus;
	}

	public void setProductStutus(String productStutus) {
		ProductStutus = productStutus;
	}

}
